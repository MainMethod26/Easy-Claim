#!/usr/bin/env node
// Seeds the demo accounts (src/security/demoUsers.ts) into the LOCAL D1 database with the password
// from DEMO_LOGIN_PASSWORD in backend/.dev.vars (agreed demo password: 1234567).
//   npm run db:seed:users:local
// Hashes are PBKDF2-SHA256, the same format the Worker verifies (src/security/password.ts).
// The generated SQL is written under .wrangler/tmp (gitignored) and executed with wrangler.
// LOCAL / DEMO ONLY: never run this against a Worker that holds real data. To bootstrap a real
// deployment create ONE superadmin with a strong password:
//   node scripts/seed-demo-users.mjs --remote --only superadmin --password '<strong password>'
import { randomBytes, webcrypto } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const backendDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const args = Object.fromEntries(
  process.argv.slice(2).map((a, i, all) => (a.startsWith('--') ? [a.slice(2), all[i + 1]?.startsWith('--') || all[i + 1] === undefined ? true : all[i + 1]] : [])).filter((x) => x.length)
)

function devVar(name) {
  const file = path.join(backendDir, '.dev.vars')
  if (!existsSync(file)) return undefined
  const m = readFileSync(file, 'utf8').match(new RegExp(`^${name}=(.*)$`, 'm'))
  return m ? m[1].trim() : undefined
}

// Same list as src/security/demoUsers.ts (kept in sync by test/demoUsers.test.ts).
const DEMO_USERS = [
  { id: 'usr_superadmin', username: 'superadmin', role: 'SUPERADMIN', tenantId: null, displayName: 'EasyClaim Platform Admin' },
  { id: 'usr_admin_discovery', username: 'admin_discovery', role: 'INSURER_ADMIN', tenantId: 'ins_discovery', displayName: 'Discovery Claims Admin' },
  { id: 'usr_admin_sanlam', username: 'admin_sanlam', role: 'INSURER_ADMIN', tenantId: 'ins_sanlam', displayName: 'Sanlam Claims Admin' },
  { id: 'user123', username: 'mike', role: 'CUSTOMER', tenantId: null, displayName: 'Mike' },
  { id: 'user456', username: 'lerato', role: 'CUSTOMER', tenantId: null, displayName: 'Lerato Nkosi' },
  { id: 'user789', username: 'sipho', role: 'CUSTOMER', tenantId: null, displayName: 'Sipho Dlamini' },
]

const ITERATIONS = 100_000
async function hashPassword(password) {
  const salt = randomBytes(16)
  const key = await webcrypto.subtle.importKey('raw', new TextEncoder().encode(password), 'PBKDF2', false, ['deriveBits'])
  const bits = await webcrypto.subtle.deriveBits({ name: 'PBKDF2', hash: 'SHA-256', salt, iterations: ITERATIONS }, key, 256)
  return `pbkdf2-sha256$${ITERATIONS}$${salt.toString('base64')}$${Buffer.from(bits).toString('base64')}`
}

const password = typeof args.password === 'string' ? args.password : devVar('DEMO_LOGIN_PASSWORD')
if (!password || password === 'CHANGE_ME' || password.length < 6) {
  console.error('No demo password: set DEMO_LOGIN_PASSWORD in backend/.dev.vars (npm run setup:local) or pass --password.')
  process.exit(1)
}
const users = args.only ? DEMO_USERS.filter((u) => u.username === args.only) : DEMO_USERS
if (!users.length) {
  console.error(`--only ${args.only}: no such demo user`)
  process.exit(1)
}
if (args.remote && users.length > 1) {
  console.error('Refusing to seed every demo account remotely. Use --only superadmin with a strong --password.')
  process.exit(1)
}

const sql = (s) => `'${String(s).replace(/'/g, "''")}'`
const lines = ['-- generated by scripts/seed-demo-users.mjs; do not commit']
for (const u of users) {
  const hash = await hashPassword(password)
  lines.push(
    `INSERT OR REPLACE INTO users (id, username, password_hash, role, tenant_id, display_name, status, created_at, created_by) VALUES (` +
      [u.id, u.username, hash, u.role, u.tenantId, u.displayName].map((v) => (v === null ? 'NULL' : sql(v))).join(', ') +
      `, 'active', strftime('%Y-%m-%dT%H:%M:%SZ','now'), NULL);`
  )
}
const outDir = path.join(backendDir, '.wrangler', 'tmp')
mkdirSync(outDir, { recursive: true })
const file = path.join(outDir, 'demo_users.sql')
writeFileSync(file, lines.join('\n') + '\n')

const wrangler = process.platform === 'win32' ? 'npx.cmd' : 'npx'
execFileSync(wrangler, ['wrangler', 'd1', 'execute', 'easy-claim-db', args.remote ? '--remote' : '--local', `--file=${file}`], { stdio: 'inherit', cwd: backendDir, shell: process.platform === 'win32' })
console.log(`Seeded ${users.length} account(s): ${users.map((u) => `${u.username} (${u.role})`).join(', ')}. Password: DEMO_LOGIN_PASSWORD in backend/.dev.vars (not shown).`)
